/**
 * Returns the localized visual display label for a skill based on language.
 * Falls back safely to the original English skill name if not found.
 *
 * @param {string} skillName - Canonical English skill name (e.g. "Solar Panel Installation")
 * @param {string} currentLanguage - Current i18n language code (e.g. "hi", "mr-IN", "or")
 * @returns {string} Translated skill display label
 */
export function getSkillLabel(skillName, currentLanguage = 'en') {
  if (!skillName || typeof skillName !== 'string') {
    return skillName || '';
  }

  const trimmed = skillName.trim();
  const langCode = (currentLanguage || 'en').split('-')[0].toLowerCase();

  const skillEntry = SKILL_LABELS[trimmed] || SKILL_LABELS[skillName];
  if (skillEntry && skillEntry[langCode]) {
    return skillEntry[langCode];
  }

  return skillName;
}

export default getSkillLabel;
