/**
 * Filter recommendations for a given role (case-insensitive)
 */
export function getRecommendationsForRole(roleName) {
  if (!roleName) return [];
  const normalized = roleName.trim().toLowerCase();
  return RECOMMENDATIONS.filter(
    (item) => item.role && item.role.toLowerCase() === normalized
  );
}

/**
 * Filter recommendations for a specific skill (case-insensitive)
 */
export function getRecommendationsForSkill(skillName) {
  if (!skillName) return [];
  const normalized = skillName.trim().toLowerCase();
  return RECOMMENDATIONS.filter(
    (item) => item.skill && item.skill.toLowerCase() === normalized
  );
}

export default RECOMMENDATIONS;
