/**
 * Safely lookup required skills for any role (case-insensitive & trimmed)
 */
export function getRequiredSkillsForRole(roleName) {
  if (!roleName) return [];
  const normalized = roleName.trim().toLowerCase();
  for (const [role, skills] of Object.entries(ROLE_REQUIRED_SKILLS)) {
    if (role.toLowerCase() === normalized) {
      return skills;
    }
  }
  return [];
}

